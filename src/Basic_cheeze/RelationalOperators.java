package Basic_cheeze;

public class RelationalOperators {
    public static void main (String[] args){
        int a = 6;
        int b = 7;
        System.out.println(a>b);
        System.out.println(a<b);
        System.out.println(a==b);
        System.out.println(a!=b);
        System.out.println(a<=b);

        boolean x = (6>3);
        System.out.println(x);
    }
}
