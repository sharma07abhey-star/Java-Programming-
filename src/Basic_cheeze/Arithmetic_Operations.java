package Basic_cheeze;

public class Arithmetic_Operations {
    public static void main(String[] args){
        int a = 5 ;
        System.out.println(a);
        a = a + 5;
        System.out.println(a);
        a = a - 2;
        System.out.println(a);
        a = a * a;
        System.out.println(a);
        a = a/3;
        System.out.println(a);

        double y = 10;
        double z = 39;
        System.out.println(z/y);
    }
}
